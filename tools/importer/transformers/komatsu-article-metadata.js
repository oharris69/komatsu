/**
 * Transformer: Komatsu article page metadata.
 *
 * Active only on pages with the article layout (.article__details-container).
 * No-op on every other page (the homepage has no such element).
 *
 * Selectors verified against migration-work/cleaned.html (Newberry newsroom article):
 *   .article__details-container #articleLeft .articledetail_contents ul.all_details
 *     > li  (first, img[alt="calendar"])  <p>October 5, 2026</p>
 *     > li.articledetail_contact           author contact (parsed by columns-article-rail; untouched)
 *     > li  (plain)                        <p>Press release, Company, Construction</p>
 *     > li.social                          share actions (generated by block JS)
 *   #articleRight .articleheader > div > p  "3 min read" label above the H1
 *
 * Runs in beforeTransform: the rail is replaced by the columns-article-rail
 * parser between hooks, so the values must be read first. Values are written
 * as <meta name="..." data-komatsu-article-meta> tags in document.head.
 *
 * NOTE: WebImporter.rules.createMetadata only reads title, description, og:* and
 * twitter:* from the head, so it does not pick these tags up by itself. The
 * import script must use createMetadataWithArticleFields() (exported below) in
 * place of WebImporter.rules.createMetadata(main, document). That way there is
 * still one Metadata block. Without article meta tags it does the same thing as
 * createMetadata.
 */
const TransformHook = { beforeTransform: 'beforeTransform', afterTransform: 'afterTransform' };
const META_ATTR = 'data-komatsu-article-meta';
const READ_TIME_RE = /(\d+)\s*min(?:ute)?s?\s*read/i;

const clean = (s) => (s || '').replace(/\s+/g, ' ').trim();

function setMeta(doc, name, content) {
  if (!content) return;
  const head = doc.head || doc.querySelector('head');
  if (!head) return;
  let meta = head.querySelector(`meta[${META_ATTR}][name="${name}"]`);
  if (!meta) {
    meta = doc.createElement('meta');
    meta.setAttribute('name', name);
    meta.setAttribute(META_ATTR, '');
    head.append(meta);
  }
  meta.setAttribute('content', content);
}

function extractTags(li) {
  // Pills (one element per tag), if the live DOM renders them that way.
  const pills = [...li.querySelectorAll('li, span, a')].map((el) => clean(el.textContent)).filter(Boolean);
  const list = pills.length > 1
    ? pills
    : clean((li.querySelector('p') || li).textContent).split(',').map(clean).filter(Boolean);
  return [...new Set(list)].join(', ');
}

export default function transform(hookName, element, payload) {
  if (hookName !== TransformHook.beforeTransform) return;

  const container = element.querySelector('.article__details-container');
  if (!container) return; // not an article layout page
  const doc = element.ownerDocument || document;

  // Rail: date + tags (author contact and social are left for the parser / block JS).
  const items = [...container.querySelectorAll('#articleLeft .articledetail_contents ul.all_details > li')]
    .filter((li) => !li.classList.contains('articledetail_contact') && !li.classList.contains('social'));

  const dateLi = items.find((li) => li.querySelector('img[alt="calendar"]')) || items[0];
  const publicationDate = dateLi ? clean((dateLi.querySelector('p') || dateLi).textContent) : '';

  const tagsLi = items.find((li) => li !== dateLi && clean(li.textContent));
  const tags = tagsLi ? extractTags(tagsLi) : '';

  // Read time label above the H1; remove it from the body after reading.
  let readTime = '';
  const header = container.querySelector('#articleRight .articleheader');
  if (header) {
    const label = [...header.querySelectorAll('p')].find((p) => READ_TIME_RE.test(p.textContent));
    if (label) {
      readTime = label.textContent.match(READ_TIME_RE)[1];
      label.remove();
    }
  }

  setMeta(doc, 'publication-date', publicationDate);
  setMeta(doc, 'tags', tags);
  setMeta(doc, 'read-time', readTime);
  setMeta(doc, 'template', 'article');
}

/**
 * Use this in the import script in place of WebImporter.rules.createMetadata(main, document).
 * It builds one Metadata block with the standard fields plus the article fields
 * written above. Without article meta tags it gives the same result as createMetadata.
 *
 * It is exposed as a property of the default export, because this file may only
 * have a default export:
 *   import articleMetadataTransformer from './transformers/komatsu-article-metadata.js';
 *   articleMetadataTransformer.createMetadataWithArticleFields(main, document);
 */
function createMetadataWithArticleFields(main, document) {
  const meta = WebImporter.Blocks.getMetadata(document) || {};
  document.querySelectorAll(`head meta[${META_ATTR}]`).forEach((m) => {
    const name = m.getAttribute('name');
    const content = m.getAttribute('content');
    if (name && content) meta[name] = content;
  });
  if (Object.keys(meta).length > 0) {
    main.append(WebImporter.Blocks.getMetadataBlock(document, meta));
  }
}

transform.createMetadataWithArticleFields = createMetadataWithArticleFields;
